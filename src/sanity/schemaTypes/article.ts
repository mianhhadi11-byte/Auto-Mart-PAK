import { defineArrayMember, defineField, defineType } from 'sanity';

export const articleType = defineType({
  name: 'article',
  title: 'Article',
  type: 'document',
  groups: [
    { name: 'content', title: 'Story', default: true },
    { name: 'media', title: 'Media' },
    { name: 'publishing', title: 'Publishing' },
    { name: 'seo', title: 'SEO & social' },
    { name: 'sources', title: 'Sources & AI' },
  ],
  fields: [
    defineField({
      name: 'title',
      title: 'Headline',
      type: 'string',
      group: 'content',
      validation: (rule) => rule.required().min(8).max(180),
    }),
    defineField({
      name: 'slug',
      title: 'Slug',
      type: 'slug',
      group: 'content',
      options: { source: 'title', maxLength: 96 },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'excerpt',
      title: 'Standfirst / summary',
      type: 'text',
      rows: 3,
      group: 'content',
      validation: (rule) => rule.required().min(20).max(420),
    }),
    defineField({
      name: 'body',
      title: 'Body',
      type: 'array',
      group: 'content',
      of: [
        defineArrayMember({
          type: 'block',
          styles: [
            { title: 'Paragraph', value: 'normal' },
            { title: 'Heading 2', value: 'h2' },
            { title: 'Heading 3', value: 'h3' },
            { title: 'Quote', value: 'blockquote' },
          ],
          lists: [
            { title: 'Bullet', value: 'bullet' },
            { title: 'Numbered', value: 'number' },
          ],
          marks: {
            decorators: [
              { title: 'Strong', value: 'strong' },
              { title: 'Emphasis', value: 'em' },
              { title: 'Code', value: 'code' },
            ],
            annotations: [
              {
                name: 'link',
                title: 'Link',
                type: 'object',
                fields: [
                  defineField({ name: 'href', title: 'URL', type: 'url', validation: (rule) => rule.required() }),
                ],
              },
            ],
          },
        }),
      ],
      validation: (rule) => rule.required().min(1),
    }),
    defineField({
      name: 'category',
      title: 'Desk',
      type: 'reference',
      to: [{ type: 'category' }],
      group: 'content',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'categorySlug',
      title: 'Category slug (legacy fallback)',
      type: 'string',
      group: 'content',
      hidden: true,
    }),
    defineField({
      name: 'author',
      title: 'Author',
      type: 'reference',
      to: [{ type: 'author' }],
      group: 'content',
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'authorId',
      title: 'Author ID (legacy fallback)',
      type: 'string',
      group: 'content',
      hidden: true,
    }),
    defineField({
      name: 'image',
      title: 'Lead image',
      type: 'image',
      group: 'media',
      options: { hotspot: true },
      fields: [
        defineField({ name: 'alt', title: 'Alt text', type: 'string' }),
        defineField({ name: 'credit', title: 'Credit', type: 'string' }),
      ],
    }),
    defineField({ name: 'imageAlt', title: 'Alt text', type: 'string', group: 'media' }),
    defineField({ name: 'imageCredit', title: 'Image credit', type: 'string', group: 'media' }),
    defineField({
      name: 'videoUrl',
      title: 'Video URL',
      type: 'url',
      group: 'media',
      description: 'YouTube/Vimeo link or a path to an MP4 in /public/videos.',
    }),
    defineField({
      name: 'status',
      title: 'Status',
      type: 'string',
      group: 'publishing',
      initialValue: 'draft',
      options: {
        layout: 'radio',
        list: [
          { title: 'Draft', value: 'draft' },
          { title: 'In review', value: 'review' },
          { title: 'Scheduled', value: 'scheduled' },
          { title: 'Published', value: 'published' },
          { title: 'Archived', value: 'archived' },
        ],
      },
      validation: (rule) => rule.required(),
    }),
    defineField({
      name: 'publishedAt',
      title: 'Publish date & time (UTC)',
      type: 'datetime',
      group: 'publishing',
    }),
    defineField({ name: 'featured', title: 'Featured', type: 'boolean', group: 'publishing', initialValue: false }),
    defineField({ name: 'trending', title: 'Trending', type: 'boolean', group: 'publishing', initialValue: false }),
    defineField({ name: 'breaking', title: 'Breaking', type: 'boolean', group: 'publishing', initialValue: false }),
    defineField({
      name: 'tags',
      title: 'Tags',
      type: 'array',
      of: [defineArrayMember({ type: 'string' })],
      group: 'publishing',
      options: { layout: 'tags' },
      validation: (rule) => rule.max(12),
    }),
    defineField({ name: 'readMinutes', title: 'Read time (minutes)', type: 'number', group: 'publishing', initialValue: 1 }),
    defineField({ name: 'views', title: 'Views', type: 'number', group: 'publishing', initialValue: 0 }),
    defineField({
      name: 'rating',
      title: 'Review score (0–10)',
      type: 'number',
      group: 'publishing',
      validation: (rule) => rule.min(0).max(10),
    }),
    defineField({ name: 'seoTitle', title: 'SEO title', type: 'string', group: 'seo', validation: (rule) => rule.max(70) }),
    defineField({
      name: 'seoDescription',
      title: 'Meta description',
      type: 'text',
      rows: 2,
      group: 'seo',
      validation: (rule) => rule.max(170),
    }),
    defineField({ name: 'socialCaption', title: 'Social caption', type: 'text', rows: 3, group: 'seo' }),
    defineField({ name: 'sourceName', title: 'Primary source name', type: 'string', group: 'sources' }),
    defineField({ name: 'sourceUrl', title: 'Primary source URL', type: 'url', group: 'sources' }),
    defineField({
      name: 'aiAssisted',
      title: 'AI-assisted draft',
      type: 'boolean',
      group: 'sources',
      initialValue: false,
      description: 'Tick when an AI assistant helped with the draft. A human editor must still verify and publish.',
    }),
    defineField({ name: 'editorId', title: 'Last editor ID', type: 'string', group: 'sources', hidden: true }),
  ],
  preview: {
    select: { title: 'title', subtitle: 'status', media: 'image' },
    prepare({ title, subtitle, media }) {
      return { title: title || 'Untitled', subtitle: String(subtitle || 'draft').toUpperCase(), media };
    },
  },
});
